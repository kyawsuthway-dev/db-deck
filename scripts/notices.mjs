// Writes THIRD_PARTY_NOTICES.md: the license of every npm package whose code ends up in DB Deck's bundles
// (the extension and the webviews), from esbuild's metafile. Run through `task notices` after adding or
// upgrading a runtime dependency. No dependencies; runs in the Docker `node` service.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [metaPath] = process.argv.slice(2);
if (!metaPath) throw new Error('Usage: node scripts/notices.mjs <esbuild metafile>');
const { inputs } = JSON.parse(readFileSync(metaPath, 'utf8'));

// node_modules/a/node_modules/@scope/b/lib/x.js → node_modules/a/node_modules/@scope/b
const packageDirs = new Set();
for (const file of Object.keys(inputs)) {
  const m = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(file);
  if (m) packageDirs.add(m[1]);
}

const ALLOWED = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|CC0-1\.0|Unlicense)$/;
const packages = new Map();
const problems = [];
for (const dir of packageDirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (packages.has(key)) continue;
  // `license` (SPDX), or the older `licenses: [{ type }]` some packages still use.
  const license =
    typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : '(none given)');
  const text = licenseText(dir);
  // `A OR B` lets DB Deck take either license, so one allowed alternative is enough; `A AND B` needs both.
  const alternatives = license.replace(/[()]/g, '').split(/\s+OR\s+/).map((alt) => alt.split(/\s+AND\s+/));
  if (!alternatives.some((ids) => ids.every((id) => ALLOWED.test(id)))) problems.push(`${key}: ${license}`);
  if (!text) problems.push(`${key}: no license file in the package (license field: ${license})`);
  packages.set(key, { name: pkg.name, version: pkg.version, license, text, homepage: pkg.homepage ?? pkg.repository?.url ?? pkg.repository });
}

/** The package's license file, or else the "License" section of its README (some packages ship only that). */
function licenseText(dir) {
  const files = readdirSync(dir);
  const file = files.find((f) => /^(licen[cs]e|copying)([.-].*)?$/i.test(f));
  if (file) return readFileSync(join(dir, file), 'utf8').trim();
  const readme = files.find((f) => /^readme(\.md)?$/i.test(f));
  if (!readme) return undefined;
  const m = /^(#+) *licen[cs]e\s*$([\s\S]*?)(?=^#{1,6} |(?![\s\S]))/im.exec(readFileSync(join(dir, readme), 'utf8'));
  return m?.[2].trim() || undefined;
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
