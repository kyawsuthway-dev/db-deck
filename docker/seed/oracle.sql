-- Objects for the tree: an index, a sequence, a trigger, a function, a procedure and a package.
CREATE INDEX orders_status_idx ON orders (status, UPPER(status));
CREATE SEQUENCE invoice_numbers START WITH 1000;

CREATE OR REPLACE TRIGGER orders_status_check
  BEFORE INSERT OR UPDATE ON orders FOR EACH ROW
BEGIN
  IF :NEW.status IS NULL THEN
    :NEW.status := 'pending';
  END IF;
END;
/

CREATE OR REPLACE FUNCTION order_total(p_customer NUMBER) RETURN NUMBER IS
  v_total NUMBER;
BEGIN
  SELECT NVL(SUM(total), 0) INTO v_total FROM orders WHERE customer_id = p_customer;
  RETURN v_total;
END;
/

CREATE OR REPLACE PROCEDURE greet(p_name VARCHAR2) IS
BEGIN
  DBMS_OUTPUT.PUT_LINE('Hello, ' || p_name);
END;
/

CREATE OR REPLACE PACKAGE shop AS
  FUNCTION paid_count RETURN NUMBER;
END shop;
/

CREATE OR REPLACE PACKAGE BODY shop AS
  FUNCTION paid_count RETURN NUMBER IS
    n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM orders WHERE status = 'paid';
    RETURN n;
  END;
END shop;
/
