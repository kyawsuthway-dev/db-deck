import { Client, type CustomTypesConfig, type QueryResult } from 'pg';
import { splitSql } from '../query/splitSql';
import type {
  Cell,
  ChangeStatement,
  ColumnInfo,
  ConnectionConfig,
  DbObject,
  Driver,
  FilterOperator,
  IndexInfo,
  RowChange,
  SslMode,
  StatementResult,
  StreamOpener,
  TableInfo,
  TablePage,
} from '../types';
import {
  buildChangeStatements,
  buildCountQuery,
  buildPageQuery,
  ChangeConflict,
  countFrom,
  FILTER_OPERATORS,
  filterCondition,
  identifierFor,
  insertStatements,
  quoteIdent,
  runEach,
  standardLiteral,
  type WriteDialect,
} from './common';

const BOOL_OID = 16;

/** PostgreSQL has no SHOW CREATE TABLE, so this DDL is rebuilt and may leave things out. */
const GENERATED_NOTE =
  '-- Generated by DB Deck from the catalog. Partitioning, inheritance, storage options, ownership and grants aren’t included.';

const WRITE_DIALECT: WriteDialect = {
  quote: '"',
  placeholder: (n) => `$${n}`,
  nullSafeEquals: 'IS NOT DISTINCT FROM',
  allDefaults: 'DEFAULT VALUES',
  literal: standardLiteral,
  asText: (column) => `${column}::text`,
};

/** Keep PostgreSQL's own text form for every value (exact numerics, timestamps as stored), except booleans. */
const textTypes: CustomTypesConfig = {
  getTypeParser: ((oid: number) =>
    oid === BOOL_OID ? (v: string) => (v === 't' ? 'true' : 'false') : (v: string) => v) as CustomTypesConfig['getTypeParser'],
};

export class PostgresDriver implements Driver {
  private client?: Client;
  private connecting?: Promise<Client>;

  constructor(
    private readonly config: ConnectionConfig,
    private readonly password: string | undefined,
    /** Set when the connection goes through an SSH tunnel. */
    private readonly opener?: StreamOpener,
  ) {}

  async connect(): Promise<void> {
    await this.getClient();
  }

  async listTables(): Promise<TableInfo[]> {
    const client = await this.getClient();
    const { rows } = await client.query<{ schema: string; name: string; type: string }>(
      `SELECT table_schema AS schema, table_name AS name, table_type AS type
         FROM information_schema.tables
        WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
       UNION ALL
       SELECT schemaname, matviewname, 'VIEW' FROM pg_matviews`,
    );
    return rows
      .map((r): TableInfo => ({
        name: r.name,
        schema: r.schema === 'public' ? undefined : r.schema,
        kind: r.type === 'VIEW' ? 'view' : 'table',
      }))
      .sort((a, b) => (a.schema ?? '').localeCompare(b.schema ?? '') || a.name.localeCompare(b.name));
  }

  async listColumns(table: TableInfo): Promise<ColumnInfo[]> {
    const client = await this.getClient();
    const { rows } = await client.query<{ name: string; type: string; nullable: string; pk: string }>(
      `SELECT a.attname AS name,
              format_type(a.atttypid, a.atttypmod) AS type,
              NOT a.attnotnull AS nullable,
              COALESCE(a.attnum = ANY (i.indkey), false) AS pk
         FROM pg_attribute a
         LEFT JOIN pg_index i ON i.indrelid = a.attrelid AND i.indisprimary
        WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum`,
      [qualifiedName(table)],
    );
    return rows.map((r) => ({ name: r.name, type: r.type, nullable: r.nullable === 'true', primaryKey: r.pk === 'true' }));
  }

  async listObjects(): Promise<DbObject[]> {
    const client = await this.getClient();
    const schemaOf = (s: string) => (s === 'public' ? undefined : s);
    const { rows: relations } = await client.query<{ schema: string; name: string; type: string }>(
      `SELECT table_schema AS schema, table_name AS name, table_type AS type
         FROM information_schema.tables
        WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
       UNION ALL
       SELECT schemaname, matviewname, 'MATVIEW' FROM pg_matviews`,
    );
    // Functions and procedures that belong to an extension (e.g. pgcrypto) are left out, like PostgreSQL's \df does with \dx members.
    const { rows: routines } = await client.query<{ id: string; schema: string; name: string; kind: string; args: string }>(
      `SELECT p.oid::text AS id, n.nspname AS schema, p.proname AS name, p.prokind AS kind,
              pg_get_function_identity_arguments(p.oid) AS args
         FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname NOT IN ('pg_catalog', 'information_schema') AND n.nspname NOT LIKE 'pg\\_toast%'
          AND p.prokind IN ('f', 'p')
          AND NOT EXISTS (SELECT 1 FROM pg_depend d
                           WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')
        ORDER BY n.nspname, p.proname, args`,
    );
    const { rows: sequences } = await client.query<{ schema: string; name: string }>(
      `SELECT schemaname AS schema, sequencename AS name FROM pg_sequences
        WHERE schemaname NOT IN ('pg_catalog', 'information_schema') ORDER BY 1, 2`,
    );
    const objects: DbObject[] = [
      ...relations.map((r): DbObject => ({
        kind: r.type === 'VIEW' || r.type === 'MATVIEW' ? 'view' : 'table',
        name: r.name,
        schema: schemaOf(r.schema),
        detail: r.type === 'MATVIEW' ? 'materialized' : undefined,
      })),
      ...routines.map((r): DbObject => ({
        kind: r.kind === 'p' ? 'procedure' : 'function',
        name: r.name,
        schema: schemaOf(r.schema),
        id: r.id,
        detail: `(${r.args})`,
      })),
      ...sequences.map((r): DbObject => ({ kind: 'sequence', name: r.name, schema: schemaOf(r.schema) })),
    ];
    return objects.sort((a, b) => (a.schema ?? '').localeCompare(b.schema ?? '') || a.name.localeCompare(b.name));
  }

  async listIndexes(table: TableInfo): Promise<IndexInfo[]> {
    const client = await this.getClient();
    const { rows } = await client.query<{ name: string; columns: string; unique: string; primary: string }>(
      `SELECT i.relname AS name, ix.indisunique AS unique, ix.indisprimary AS primary,
              (SELECT string_agg(pg_get_indexdef(ix.indexrelid, k + 1, true), ', ' ORDER BY k)
                 FROM generate_series(0, ix.indnkeyatts - 1) k) AS columns
         FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid
        WHERE ix.indrelid = $1::regclass
        ORDER BY ix.indisprimary DESC, i.relname`,
      [qualifiedName(table)],
    );
    return rows.map((r) => ({ name: r.name, columns: r.columns ?? '', unique: r.unique === 'true', primary: r.primary === 'true' }));
  }

  async listTriggers(table: TableInfo): Promise<DbObject[]> {
    const client = await this.getClient();
    const { rows } = await client.query<{ name: string; detail: string | null }>(
      `SELECT t.tgname AS name,
              substring(pg_get_triggerdef(t.oid) from ' ((?:BEFORE|AFTER|INSTEAD OF) .+?) ON ') AS detail
         FROM pg_trigger t
        WHERE t.tgrelid = $1::regclass AND NOT t.tgisinternal
        ORDER BY t.tgname`,
      [qualifiedName(table)],
    );
    return rows.map((r) => ({ kind: 'trigger', name: r.name, schema: table.schema, table: table.name, detail: r.detail ?? undefined }));
  }

  /**
   * PostgreSQL's own functions for views, routines, triggers and indexes. Tables and sequences have none,
   * so their DDL is rebuilt from the catalog, and says so.
   */
  async objectDdl(object: DbObject): Promise<string> {
    const client = await this.getClient();
    const one = async (sql: string, params: unknown[]) => {
      const { rows } = await client.query<{ def: string | null }>(sql, params);
      return rows[0]?.def ?? null;
    };
    const end = (sql: string) => `${sql.trim().replace(/;$/, '')};\n`;
    const name = qualifiedName(object);
    const missing = `-- No definition found for ${object.name}.\n`;
    switch (object.kind) {
      case 'view': {
        const def = await one('SELECT pg_get_viewdef($1::regclass, true) AS def', [name]);
        if (def === null) return missing;
        const create = object.detail === 'materialized' ? 'CREATE MATERIALIZED VIEW' : 'CREATE OR REPLACE VIEW';
        return end(`${create} ${name} AS\n${def}`);
      }
      case 'function':
      case 'procedure': {
        if (!object.id || !/^\d+$/.test(object.id)) return missing;
        const def = await one('SELECT pg_get_functiondef($1::oid) AS def', [object.id]);
        return def === null ? missing : end(def);
      }
      case 'trigger': {
        const def = await one(
          'SELECT pg_get_triggerdef(oid, true) AS def FROM pg_trigger WHERE tgrelid = $1::regclass AND tgname = $2',
          [qualifiedName({ name: object.table ?? '', schema: object.schema }), object.name],
        );
        return def === null ? missing : end(def);
      }
      case 'index': {
        const def = await one('SELECT pg_get_indexdef($1::regclass) AS def', [name]);
        return def === null ? missing : end(def);
      }
      case 'sequence':
        return this.sequenceDdl(object, name);
      case 'table':
        return this.tableDdl(name);
    }
  }

  async listDatabases(): Promise<string[]> {
    const client = await this.getClient();
    const { rows } = await client.query<{ name: string }>(
      'SELECT datname AS name FROM pg_database WHERE datallowconn AND NOT datistemplate ORDER BY datname',
    );
    return rows.map((r) => r.name);
  }

  defaultSchemaLabel(): string | undefined {
    return 'public';
  }

  private async sequenceDdl(object: DbObject, name: string): Promise<string> {
    const client = await this.getClient();
    const { rows } = await client.query<Record<string, string>>(
      `SELECT data_type, start_value, min_value, max_value, increment_by, cycle, cache_size
         FROM pg_sequences WHERE schemaname = $1 AND sequencename = $2`,
      [object.schema ?? 'public', object.name],
    );
    const s = rows[0];
    if (!s) return `-- No definition found for ${object.name}.\n`;
    return [
      GENERATED_NOTE,
      `CREATE SEQUENCE ${name}`,
      `  AS ${s.data_type}`,
      `  INCREMENT BY ${s.increment_by}`,
      `  MINVALUE ${s.min_value}`,
      `  MAXVALUE ${s.max_value}`,
      `  START WITH ${s.start_value}`,
      `  CACHE ${s.cache_size}`,
      `  ${s.cycle === 'true' ? 'CYCLE' : 'NO CYCLE'};`,
      '',
    ].join('\n');
  }

  private async tableDdl(name: string): Promise<string> {
    const client = await this.getClient();
    const { rows: columns } = await client.query<{ name: string; type: string; notnull: string; def: string | null; identity: string; generated: string }>(
      `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS notnull,
              pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity AS identity, a.attgenerated AS generated
         FROM pg_attribute a
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum`,
      [name],
    );
    if (!columns.length) return `-- No definition found for ${name}.\n`;
    const { rows: constraints } = await client.query<{ name: string; def: string }>(
      `SELECT conname AS name, pg_get_constraintdef(oid, true) AS def FROM pg_constraint
        WHERE conrelid = $1::regclass AND contype IN ('p', 'u', 'f', 'c', 'x')
        ORDER BY contype = 'p' DESC, contype = 'u' DESC, conname`,
      [name],
    );
    // Indexes that aren't the ones behind PRIMARY KEY / UNIQUE / EXCLUDE constraints.
    const { rows: indexes } = await client.query<{ def: string }>(
      `SELECT pg_get_indexdef(ix.indexrelid) AS def FROM pg_index ix
        WHERE ix.indrelid = $1::regclass
          AND ix.indexrelid NOT IN (SELECT conindid FROM pg_constraint
                                     WHERE conrelid = $1::regclass AND contype IN ('p', 'u', 'x'))
        ORDER BY 1`,
      [name],
    );
    const lines = columns.map((c) => {
      let line = `  ${this.filterIdentifier(c.name)} ${c.type}`;
      if (c.identity === 'a') line += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.identity === 'd') line += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.generated === 's' && c.def) line += ` GENERATED ALWAYS AS (${c.def}) STORED`;
      else if (c.def) line += ` DEFAULT ${c.def}`;
      if (c.notnull === 'true' && !c.identity) line += ' NOT NULL';
      return line;
    });
    lines.push(...constraints.map((c) => `  CONSTRAINT ${this.filterIdentifier(c.name)} ${c.def}`));
    return [GENERATED_NOTE, `CREATE TABLE ${name} (`, lines.join(',\n'), ');', ...indexes.map((i) => `${i.def};`), ''].join('\n');
  }

  async query(sql: string): Promise<StatementResult[]> {
    const client = await this.getClient();
    return runEach(splitSql(sql, 'postgres'), async (statement) => {
      const res: unknown = await client.query({ text: statement, rowMode: 'array' });
      // If the splitter ever leaves two statements together, pg returns an array; show the last.
      const r = (Array.isArray(res) ? res[res.length - 1] : res) as QueryResult<unknown[]>;
      const columns = r.fields.map((f) => f.name);
      return { columns, rows: r.rows, affectedRows: columns.length === 0 ? (r.rowCount ?? undefined) : undefined };
    });
  }

  previewSql(table: TableInfo, page: TablePage): string {
    return buildPageQuery(qualifiedName(table), '"', page);
  }

  async selectPage(table: TableInfo, page: TablePage, where?: string): Promise<StatementResult> {
    const sql = buildPageQuery(qualifiedName(table), '"', page, filterCondition(where, 'postgres'));
    const client = await this.getClient();
    const [result] = await runEach([sql], async (statement) => {
      const r = await client.query<unknown[]>({ text: statement, rowMode: 'array' });
      return { columns: r.fields.map((f) => f.name), rows: r.rows };
    });
    return result;
  }

  async countRows(table: TableInfo, where?: string): Promise<string> {
    const sql = buildCountQuery(qualifiedName(table), filterCondition(where, 'postgres'));
    const client = await this.getClient();
    const [result] = await runEach([sql], async (statement) => {
      const r = await client.query<unknown[]>({ text: statement, rowMode: 'array' });
      return { columns: r.fields.map((f) => f.name), rows: r.rows };
    });
    return countFrom(result);
  }

  /** Unquoted names fold to lowercase in PostgreSQL, so anything with uppercase must be quoted. */
  filterIdentifier(name: string): string {
    return identifierFor(name, '"', /^[a-z_][a-z0-9_]*$/);
  }

  insertSql(table: TableInfo, columns: string[], rows: Cell[][]): string {
    return insertStatements(qualifiedName(table), '"', columns, rows, standardLiteral);
  }

  filterOperators(): FilterOperator[] {
    const likeAt = FILTER_OPERATORS.findIndex((o) => o.label === 'NOT LIKE') + 1;
    return [
      ...FILTER_OPERATORS.slice(0, likeAt),
      { label: 'ILIKE', insert: 'ILIKE ' },
      { label: 'NOT ILIKE', insert: 'NOT ILIKE ' },
      ...FILTER_OPERATORS.slice(likeAt),
    ];
  }

  async close(): Promise<void> {
    const client = this.client;
    this.client = undefined;
    await client?.end();
  }

  /** One long-lived client, so session state (transactions, SET) carries across runs. Reopened if it drops. */
  private getClient(): Promise<Client> {
    if (this.client) return Promise.resolve(this.client);
    this.connecting ??= this.open().finally(() => (this.connecting = undefined));
    return this.connecting;
  }

  changeStatements(table: TableInfo, changes: RowChange[]): ChangeStatement[] {
    return buildChangeStatements(qualifiedName(table), WRITE_DIALECT, changes);
  }

  /** On its own connection, so the editor's session (and any open transaction) is never touched. */
  async applyChanges(statements: ChangeStatement[]): Promise<void> {
    const client = await this.newClient('DB Deck (edit)');
    client.on('error', () => {}); // a dropped connection fails the pending query instead of crashing
    await client.connect();
    try {
      await client.query('BEGIN');
      for (const [i, s] of statements.entries()) {
        const r = await client.query({ text: s.sql, values: s.params });
        if (r.rowCount !== 1) throw new ChangeConflict(i, r.rowCount ?? 0);
      }
      await client.query('COMMIT');
    } catch (err) {
      await client.query('ROLLBACK').catch(() => {});
      throw err;
    } finally {
      await client.end().catch(() => {});
    }
  }

  private async newClient(applicationName: string): Promise<Client> {
    const c = this.config;
    const stream = this.opener ? await this.opener(c.host ?? 'localhost', c.port ?? 5432) : undefined;
    return new Client({
      // Through a tunnel, pg still gets the real host: TLS checks the certificate against it.
      stream: stream && (() => stream),
      host: c.host,
      port: c.port,
      user: c.user,
      password: this.password,
      database: c.database || 'postgres',
      ssl: sslOption(c.ssl),
      connectionTimeoutMillis: 10_000,
      application_name: applicationName,
      types: textTypes,
      // Read-only from the first statement, on every connection (also the edit one). Not a security boundary:
      // the session can turn it off again (README).
      options: c.readOnly ? '-c default_transaction_read_only=on' : undefined,
    });
  }

  private async open(): Promise<Client> {
    const client = await this.newClient('DB Deck');
    const drop = () => {
      if (this.client === client) this.client = undefined;
    };
    client.on('error', drop);
    client.on('end', drop);
    await client.connect();
    this.client = client;
    return client;
  }
}

function qualifiedName(table: { name: string; schema?: string }): string {
  return `${quoteIdent(table.schema ?? 'public', '"')}.${quoteIdent(table.name, '"')}`;
}

function sslOption(mode: SslMode | undefined) {
  if (mode === 'require') return true;
  if (mode === 'no-verify') return { rejectUnauthorized: false };
  return false;
}
