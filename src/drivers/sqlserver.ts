  /**
   * On its own connection in one transaction, so the editor's session (and any open transaction) is never
   * touched. Each statement reports its own @@ROWCOUNT (NOCOUNT keeps trigger counts out); any count other
   * than 1 rolls everything back. SQL Server has no read-only session, so a read-only connection refuses here.
   */
  async applyChanges(statements: ChangeStatement[]): Promise<void> {
    if (this.config.readOnly) throw new Error('This connection is read-only, so its tables can’t be edited.');
    const conn = await this.createConnection();
    try {
      await request(conn, 'SET NOCOUNT ON; SET XACT_ABORT ON; BEGIN TRANSACTION;');
      for (const [i, s] of statements.entries()) {
        const results = await request(conn, `${s.sql};\nSELECT @@ROWCOUNT;`, s.params);
        const affected = Number(results[results.length - 1]?.rows[0]?.[0]);
        if (affected !== 1) throw new ChangeConflict(i, affected);
      }
      await request(conn, 'COMMIT;');
    } catch (err) {
      await request(conn, 'IF @@TRANCOUNT > 0 ROLLBACK;').catch(() => {});
      throw err;
    } finally {
      conn.close();
    }
  }

