  /**
   * One schema's objects (system ones included: `sys` and `INFORMATION_SCHEMA` hold SQL Server's own views,
   * functions and procedures), or (no `only`) the user objects of every user schema.
   */
  private async readObjects(only?: string): Promise<DbObject[]> {
    const rows = await this.rows(
      `SELECT s.name, o.name, RTRIM(o.type)
         FROM sys.all_objects o JOIN sys.schemas s ON s.schema_id = o.schema_id
        WHERE o.type IN ('U', 'V', 'P', 'PC', 'X', 'FN', 'IF', 'TF', 'FS', 'FT', 'SO') AND o.parent_object_id = 0
          AND (s.name = @p1 OR (@p1 IS NULL AND o.is_ms_shipped = 0))
        ORDER BY s.name, o.name`,
      [only ?? null],
    );
    return rows
      .filter(([schema]) => only !== undefined || !this.isSystemSchema(String(schema)))
      .map(([schema, name, type]): DbObject => {
        const t = String(type);
        const kind: ObjectKind =
          t === 'U' ? 'table' : t === 'V' ? 'view' : t === 'SO' ? 'sequence' : ['P', 'PC', 'X'].includes(t) ? 'procedure' : 'function';
        return {
          kind,
          name: String(name),
          schema: this.schemaOf(String(schema)),
          detail: ['IF', 'TF', 'FT'].includes(t) ? 'table-valued' : t === 'X' ? 'extended' : undefined,
        };
      });
  }

  async listTreeSchemas(): Promise<SchemaEntry[]> {
    const rows = await this.rows('SELECT name FROM sys.schemas');
    return treeSchemas(rows.map(([name]) => String(name)), this.defaultSchema, (name) => this.isSystemSchema(name));
  }

  isSystemSchema(schema: string | undefined): boolean {
    return SYSTEM_SCHEMAS.has((schema ?? this.defaultSchema).toLowerCase());
  }

  async objectKinds(): Promise<ObjectKind[]> {
    return ['table', 'view', 'function', 'procedure', 'sequence'];
  }

  async listIndexes(table: TableInfo): Promise<IndexInfo[]> {
    return (await this.indexes(qualifiedName(table))).map((ix) => ({
      name: ix.name,
      columns: ix.keys.join(', ') || '(columnstore)',
      unique: ix.unique,
      primary: ix.primary,
    }));
  }

  async listTriggers(table: TableInfo): Promise<DbObject[]> {
    const rows = await this.rows(
      `SELECT t.name, t.is_instead_of_trigger, STRING_AGG(te.type_desc, ' OR ')
         FROM sys.triggers t LEFT JOIN sys.trigger_events te ON te.object_id = t.object_id
        WHERE t.parent_id = OBJECT_ID(@p1)
        GROUP BY t.name, t.is_instead_of_trigger ORDER BY t.name`,
      [qualifiedName(table)],
    );
    return rows.map(([name, insteadOf, events]) => ({
      kind: 'trigger',
      name: String(name),
      schema: table.schema,
      table: table.name,
      detail: `${insteadOf === true ? 'INSTEAD OF' : 'AFTER'} ${String(events ?? '')}`.trim(),
    }));
  }

  /**
   * Views, functions, procedures and triggers as SQL Server stored them (`OBJECT_DEFINITION`); tables, indexes
   * and sequences rebuilt from the catalog and labeled so. Never run by DB Deck.
   */
  async objectDdl(object: DbObject): Promise<string> {
    const name = qualifiedName(object);
    switch (object.kind) {
      case 'table':
        return this.tableDdl(name);
      case 'index': {
        const on = qualifiedName({ name: object.table ?? '', schema: object.schema });
        const ix = (await this.indexes(on)).find((i) => i.name === object.name);
        return ix ? `${indexDdl(on, ix)}\n` : `-- No definition found for ${object.name}.\n`;
      }
      case 'sequence':
        return this.sequenceDdl(name);
      default: {
        // A trigger is in its table's schema.
        const [[def] = []] = await this.rows('SELECT OBJECT_DEFINITION(OBJECT_ID(@p1))', [name]);
        if (def === null || def === undefined) {
          return `-- SQL Server returned no definition for ${object.name}: it was created WITH ENCRYPTION, it's built in, or you lack VIEW DEFINITION permission.\n`;
        }
        return `${String(def).trim()}\nGO\n`;
      }
    }
  }

