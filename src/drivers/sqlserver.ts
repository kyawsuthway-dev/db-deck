  /**
   * Runs the script one `GO` batch at a time, each as one request (a batch's variables and temp tables live
   * for that batch), and shows every result set. `GO n` runs its batch n times. On a read-only connection,
   * every statement is checked first and nothing runs if one may write (SQL Server has no read-only session).
   */
  async query(sql: string): Promise<StatementResult[]> {
    const batches = splitBatches(sql);
    if (this.config.readOnly) {
      for (const statement of batches.flatMap((b) => splitSql(b.sql, 'sqlserver'))) {
        const check = readingStatement(statement, 'sqlserver');
        if (!check.ok) return [{ sql: statement, columns: [], rows: [], durationMs: 0, error: check.reason }];
      }
    }
    const texts = batches.flatMap((b) => Array<string>(b.repeat).fill(b.sql));
    return runEach(texts, (text) => this.run((conn) => request(conn, text)));
  }

  previewSql(table: TableInfo, page: TablePage): string {
    return pageQuery(qualifiedName(table), page);
  }

  async selectPage(table: TableInfo, page: TablePage, where?: string): Promise<StatementResult> {
    const sql = pageQuery(qualifiedName(table), page, filterCondition(where, 'sqlserver'));
    const [result] = await runEach([sql], (statement) => this.run((conn) => single(request(conn, statement))));
    return result;
  }

  async countRows(table: TableInfo, where?: string): Promise<string> {
    const condition = filterCondition(where, 'sqlserver');
    // COUNT_BIG: COUNT returns int, which overflows past 2,147,483,647 rows.
    const sql = `SELECT COUNT_BIG(*) FROM ${qualifiedName(table)}${condition ? ` WHERE (\n${condition}\n)` : ''};`;
    const [result] = await runEach([sql], (statement) => this.run((conn) => single(request(conn, statement))));
    return countFrom(result);
  }

  /** Column names aren't case-sensitive in a default collation, so only odd characters and reserved words need brackets. */
