/** Schemas SQL Server creates in every database: browse and query only (`isSystemSchema`). */
const SYSTEM_SCHEMAS = new Set(
  ['sys', 'information_schema', 'guest', 'db_owner', 'db_accessadmin', 'db_securityadmin', 'db_ddladmin', 'db_backupoperator',
    'db_datareader', 'db_datawriter', 'db_denydatareader', 'db_denydatawriter'],
);


